import { StrictMode } from "react";
import { createRoot, hydrateRoot } from "react-dom/client";
import { SiteApp } from "./site/SiteApp.tsx";
import "@fontsource/orbitron/latin-700.css";
import "./styles/index.css";
import "./styles/calculator.css";
import "./styles/site.css";
import "./styles/settings.css";
import { registerServiceWorker } from "./registerServiceWorker.ts";
import { isStandaloneApp } from "./platforms/appEnvironment.ts";

const rootElement = document.getElementById("root")!;
const app = (
    <StrictMode>
        <SiteApp />
    </StrictMode>
);

// Only GitHub Pages HTML generated by SSG contains the route marker.
// A cached offline fallback for a different route must not be hydrated.
const prerenderedPath = rootElement.getAttribute("data-ssg-path");
const shouldHydrate = import.meta.env.MODE === "pages" &&
    prerenderedPath !== null &&
    prerenderedPath === window.location.pathname;

if (shouldHydrate) {
    hydrateRoot(rootElement, app);
} else {
    createRoot(rootElement).render(app);
}

if (import.meta.env.PROD && !isStandaloneApp) {
    registerServiceWorker();
}
